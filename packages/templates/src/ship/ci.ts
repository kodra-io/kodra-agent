import {
  helmDeployCommand,
  JENKINS_NETWORK,
  KNOWN_HOSTS,
  sshDeployCommand,
  VM_SCRIPT,
  type DeployTarget,
} from './deploy.ts';
import { CHECKOUT_ACTION, HELM, IMAGES } from './images.ts';

export interface CiOptions {
  /** Image repository without a tag. */
  image: string;
  chartDir: string;
  /** The branch whose pushes publish the image. */
  defaultBranch: string;
  /** The tests, run in the stack's pinned build image before the image is built; null for none. */
  test: CiTest | null;
  /** B6: the deploy stage, run on the default branch after everything else passed. */
  deploy?: DeployTarget | null;
}

export interface CiTest {
  image: string;
  run: string;
  env?: Readonly<Record<string, string>>;
}

/** The chart's appVersion, read in CI so the default branch also pushes that tag. */
const appVersion = (chartDir: string) =>
  `grep '^appVersion:' ${chartDir}/Chart.yaml | cut -d: -f2- | tr -d " \\"'"`;

/**
 * GitHub Actions: runs the tests, builds the image on every PR and push, and pushes it to
 * GHCR: `pr-<sha>` from a PR in this repo (not from forks), and `<sha>` and the chart's
 * appVersion from the default branch. Lints and renders the chart. Actions and Helm are pinned.
 */
export function githubWorkflow(o: CiOptions): string {
  const env = Object.entries(o.test?.env ?? {})
    .map(([k, v]) => `-e ${k}=${v} `)
    .join('');
  const test = o.test
    ? `  test:
    name: Run the tests
    runs-on: ubuntu-latest
    steps:
      - uses: ${CHECKOUT_ACTION}
      - name: Test
        run: docker run --rm ${env}-v "$PWD:/src" -w /src ${o.test.image} sh -c ${JSON.stringify(o.test.run)}

`
    : '';
  return `# Generated by Kodra AI Agent.
name: Container

on:
  pull_request:
  push:
    branches: [${JSON.stringify(o.defaultBranch)}]

permissions:
  contents: read

jobs:
${test}  image:
    name: Build the image
${o.test ? '    needs: test\n' : ''}    runs-on: ubuntu-latest
    permissions:
      contents: read
      packages: write
    env:
      IMAGE: ${o.image}
      # A PR's own head commit, not the merge commit GitHub builds.
      SHA: \${{ github.event.pull_request.head.sha || github.sha }}
    steps:
      - uses: ${CHECKOUT_ACTION}
      - name: Build
        run: docker build -t "$IMAGE:build" .
      - name: Push to GitHub Container Registry
        # PRs from forks get no write token, so only this repo's PRs push.
        if: github.event_name == 'push' || github.event.pull_request.head.repo.full_name == github.repository
        env:
          REGISTRY_TOKEN: \${{ secrets.GITHUB_TOKEN }}
        run: |
          echo "$REGISTRY_TOKEN" | docker login ghcr.io -u "$GITHUB_ACTOR" --password-stdin
          if [ "$GITHUB_EVENT_NAME" = "pull_request" ]; then
            tags="pr-$SHA"
          else
            tags="$SHA $(${appVersion(o.chartDir)})"
          fi
          for tag in $tags; do
            docker tag "$IMAGE:build" "$IMAGE:$tag"
            docker push "$IMAGE:$tag"
          done

  chart:
    name: Lint the Helm chart
    runs-on: ubuntu-latest
    env:
      HELM_VERSION: ${HELM.version}
      HELM_SHA256: ${HELM.linuxAmd64Sha256}
    steps:
      - uses: ${CHECKOUT_ACTION}
      - name: Install Helm (checksum-verified)
        run: |
          archive="helm-\${HELM_VERSION}-linux-amd64.tar.gz"
          curl -sSfL -o "$archive" "https://get.helm.sh/\${archive}"
          echo "\${HELM_SHA256}  \${archive}" | sha256sum --check
          tar -xzf "$archive" linux-amd64/helm
          sudo mv linux-amd64/helm /usr/local/bin/helm
      - run: helm lint ${o.chartDir}
      - run: helm template ci ${o.chartDir} > /dev/null
${o.deploy ? githubDeploy(o, o.deploy) : ''}`;
}

/** GitHub Actions deploy job: pushes to the default branch only, one deploy at a time. */
function githubDeploy(o: CiOptions, t: DeployTarget): string {
  const kube = t.kind === 'kubernetes';
  const file = kube ? '"$RUNNER_TEMP/kubeconfig"' : '"$RUNNER_TEMP/deploy_key"';
  const run = kube
    ? `docker run --rm -v "$PWD:/src:ro" -w /src -v ${file}:/tmp/kubeconfig:ro -e KUBECONFIG=/tmp/kubeconfig --entrypoint sh ${IMAGES.helm} -c "${helmDeployCommand(t, o.chartDir, '$IMAGE', '$SHA')}"`
    : sshDeployCommand(t, file, KNOWN_HOSTS, VM_SCRIPT, '"$IMAGE:$SHA"');
  return `
  deploy:
    name: Deploy to ${t.environment}
    needs: [image, chart]
    # Merges to the default branch only; ${t.when === 'manual' ? `the ${t.environment} environment's required reviewers approve each deploy.` : 'every merge deploys.'}
    if: github.event_name == 'push'
    runs-on: ubuntu-latest
    environment: ${t.environment}
    concurrency:
      group: deploy-${t.environment}
      cancel-in-progress: false
    permissions:
      contents: read
    env:
      IMAGE: ${o.image}
      SHA: \${{ github.sha }}
    steps:
      - uses: ${CHECKOUT_ACTION}
      - name: ${kube ? 'Deploy with Helm' : 'Deploy over SSH'}
        env:
          DEPLOY_CREDENTIALS: \${{ secrets.${t.credentials} }}
        run: |
          umask 077
          printf '%s\\n' "$DEPLOY_CREDENTIALS" > ${file}
          trap 'rm -f ${file}' EXIT
          ${run}
`;
}

export interface JenkinsOptions extends CiOptions {
  /** The Jenkins credentials (username and password) the push logs in with; none to skip login. */
  credentials?: string | undefined;
}

/** Groovy `'''` strings still read backslash escapes. */
const groovy = (s: string) => s.replaceAll('\\', '\\\\');

/**
 * A shell step that runs `script` in `image` on a copy of the workspace: `docker cp`, not a
 * bind mount, so it also works when the Jenkins agent talks to a remote Docker daemon.
 */
function inContainer(image: string, script: string, env: Readonly<Record<string, string>> = {}) {
  const e = Object.entries(env)
    .map(([k, v]) => `-e ${k}=${v} `)
    .join('');
  return `cid=$(docker create -w /src ${e}--entrypoint sh ${image} -c ${JSON.stringify(script)})
            trap 'docker rm -f "$cid" > /dev/null' EXIT
            docker cp ./. "$cid:/src"
            docker start -a "$cid"`;
}

/**
 * Jenkins (B5): a declarative pipeline that runs the tests, builds the image, lints the chart,
 * and pushes the image: `pr-<sha>` from other branches and pull requests, and `<sha>` and the
 * chart's appVersion from the default branch. Every step runs in Docker on the Jenkins agent,
 * in the same pinned images as the GitHub and GitLab pipelines, so the agent needs only Docker.
 */
export function jenkinsfile(o: JenkinsOptions): string {
  const test = o.test
    ? `
    stage('Test') {
      steps {
        sh '''
            ${groovy(inContainer(o.test.image, o.test.run, o.test.env))}
        '''
      }
    }
`
    : '';
  const push = `branch="\${BRANCH_NAME:-\${GIT_BRANCH#origin/}}"
            sha="\${GIT_COMMIT:-$(git rev-parse HEAD)}"
            if [ "$branch" = "$DEFAULT_BRANCH" ] && [ -z "$CHANGE_ID" ]; then
              tags="$sha $(grep '^appVersion:' "$CHART_DIR/Chart.yaml" | cut -d: -f2- | tr -d ' "' | tr -d "'")"
            else
              tags="pr-$sha"
            fi
${o.credentials ? `            echo "$REGISTRY_PASSWORD" | docker login "\${IMAGE%%/*}" -u "$REGISTRY_USER" --password-stdin\n` : ''}            for tag in $tags; do
              docker tag "$IMAGE:build" "$IMAGE:$tag"
              docker push "$IMAGE:$tag"
            done`;
  const pushStep = o.credentials
    ? `withCredentials([usernamePassword(credentialsId: '${o.credentials}', usernameVariable: 'REGISTRY_USER', passwordVariable: 'REGISTRY_PASSWORD')]) {
          sh '''
            ${push}
          '''
        }`
    : `sh '''
            ${push}
        '''`;
  return `// Generated by Kodra AI Agent.
// Runs on any Jenkins agent with Docker and buildx: the Dockerfile uses BuildKit's build cache.
// A multibranch pipeline builds every branch and pull
// request; with GitHub, discover pull requests by their head revision so the pr-<sha> tag
// matches the pull request's last commit.
pipeline {
  agent any
  options {
    // A manual deploy waits up to an hour for a person.
    timeout(time: ${o.deploy?.when === 'manual' ? '90' : '30'}, unit: 'MINUTES')
    disableConcurrentBuilds()
  }
  environment {
    IMAGE = '${o.image}'
    CHART_DIR = '${o.chartDir}'
    DEFAULT_BRANCH = '${o.defaultBranch}'
    // The generated Dockerfile caches dependencies with RUN --mount, which needs BuildKit:
    // without buildx, the build fails here instead of on the legacy builder.
    DOCKER_BUILDKIT = '1'
  }
  stages {${test}
    stage('Image') {
      steps {
        sh 'docker build -t "$IMAGE:build" .'
      }
    }

    stage('Chart') {
      steps {
        sh '''
            ${inContainer(IMAGES.helm, `helm lint ${o.chartDir} && helm template ci ${o.chartDir} > /dev/null`)}
        '''
      }
    }

    stage('Push') {
      steps {
        ${pushStep}
      }
    }
${o.deploy ? jenkinsDeploy(o, o.deploy) : ''}  }
  post {
    always {
      sh 'docker image rm "$IMAGE:build" > /dev/null 2>&1 || true'
    }
  }
}
`;
}

/**
 * Jenkins deploy stage (B6): the default branch only, never a pull request, in a pinned helper
 * container that gets the credentials file by `docker cp`. `DOCKER_NETWORK`, when set on the
 * agent, is the Docker network that reaches the cluster or the VM.
 */
function jenkinsDeploy(o: JenkinsOptions, t: DeployTarget): string {
  const kube = t.kind === 'kubernetes';
  const binding = kube
    ? `file(credentialsId: '${t.credentials}', variable: 'DEPLOY_FILE')`
    : `sshUserPrivateKey(credentialsId: '${t.credentials}', keyFileVariable: 'DEPLOY_FILE')`;
  const command = kube
    ? helmDeployCommand(t, o.chartDir, '$IMAGE', '$sha')
    : `chmod 600 /tmp/deploy && ${sshDeployCommand(t, '/tmp/deploy', KNOWN_HOSTS, VM_SCRIPT, '$IMAGE:$sha')}`;
  const image = kube ? IMAGES.helm : IMAGES.ssh;
  const input =
    t.when === 'manual'
      ? `
      options {
        timeout(time: 60, unit: 'MINUTES')
      }
      input {
        message 'Deploy to ${t.environment}?'
        ok 'Deploy'
      }`
      : '';
  return `
    stage('Deploy') {
      when {
        branch '${o.defaultBranch}'${t.when === 'manual' ? '\n        beforeInput true' : ''}
      }${input}
      steps {
        withCredentials([${binding}]) {
          sh '''
            sha="\${GIT_COMMIT:-$(git rev-parse HEAD)}"
            cid=$(docker create ${JENKINS_NETWORK} -w /src${kube ? ' -e KUBECONFIG=/tmp/deploy' : ''} --entrypoint sh ${image} -c "${command}")
            trap 'docker rm -f "$cid" > /dev/null' EXIT
            docker cp ./. "$cid:/src"
            docker cp "$DEPLOY_FILE" "$cid:/tmp/deploy"
            docker start -a "$cid"
          '''
        }
      }
    }
`;
}

/**
 * GitLab CI: runs the tests, builds the image with Docker-in-Docker, and pushes it to the
 * project's registry: `pr-<sha>` from other branches, and `<sha>` and the chart's appVersion
 * from the default branch. Lints and renders the chart.
 */
export function gitlabCi(o: CiOptions): string {
  const variables = Object.entries(o.test?.env ?? {})
    .map(([k, v]) => `\n    ${k}: ${JSON.stringify(v)}`)
    .join('');
  const test = o.test
    ? `test:
  stage: test
  image: ${o.test.image}${variables ? `\n  variables:${variables}` : ''}
  script:
    - ${o.test.run}

`
    : '';
  return `# Generated by Kodra AI Agent.
stages: [${o.test ? 'test, ' : ''}build, package${o.deploy ? ', deploy' : ''}]

${test}image-build:
  stage: build
  image: ${IMAGES.dockerCli}
  services:
    - ${IMAGES.dockerDind}
  variables:
    DOCKER_TLS_CERTDIR: "/certs"
  script:
    - docker build -t "$CI_REGISTRY_IMAGE:build" .
    - |
      if [ "$CI_COMMIT_BRANCH" = "$CI_DEFAULT_BRANCH" ]; then
        tags="$CI_COMMIT_SHA $(${appVersion(o.chartDir)})"
      elif [ -n "$CI_COMMIT_BRANCH" ]; then
        tags="pr-$CI_COMMIT_SHA"
      else
        tags=""
      fi
      if [ -n "$tags" ]; then
        echo "$CI_REGISTRY_PASSWORD" | docker login -u "$CI_REGISTRY_USER" --password-stdin "$CI_REGISTRY"
        for tag in $tags; do
          docker tag "$CI_REGISTRY_IMAGE:build" "$CI_REGISTRY_IMAGE:$tag"
          docker push "$CI_REGISTRY_IMAGE:$tag"
        done
      fi

chart-lint:
  stage: package
  image:
    name: ${IMAGES.helm}
    entrypoint: [""]
  script:
    - helm lint ${o.chartDir}
    - helm template ci ${o.chartDir} > /dev/null
${o.deploy ? gitlabDeploy(o, o.deploy) : ''}`;
}

/** GitLab deploy job: the default branch only, one deploy at a time per environment. */
function gitlabDeploy(o: CiOptions, t: DeployTarget): string {
  const kube = t.kind === 'kubernetes';
  const file = `"$${t.credentials}"`;
  const script = kube
    ? [
        `export KUBECONFIG=${file}`,
        helmDeployCommand(t, o.chartDir, '"$CI_REGISTRY_IMAGE"', '"$CI_COMMIT_SHA"'),
      ]
    : [
        `chmod 600 ${file}`,
        sshDeployCommand(t, file, KNOWN_HOSTS, VM_SCRIPT, '"$CI_REGISTRY_IMAGE:$CI_COMMIT_SHA"'),
      ];
  return `
deploy:
  stage: deploy
  image:
    name: ${kube ? IMAGES.helm : IMAGES.ssh}
    entrypoint: [""]
  environment:
    name: ${t.environment}
  resource_group: deploy-${t.environment}
  rules:
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
      when: ${t.when === 'manual' ? 'manual' : 'on_success'}
  script:
${script.map((l) => `    - ${l}`).join('\n')}
`;
}
